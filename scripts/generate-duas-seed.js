/**
 * Generates supabase/seed/duas_seed.sql from the single source of truth,
 * src/data/duas.ts, so the app and the database never drift apart.
 *
 * Run with: npm run seed:duas
 */
const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const root = path.resolve(__dirname, '..');
const duasFile = path.join(root, 'src', 'data', 'duas.ts');
const outFile = path.join(root, 'supabase', 'seed', 'duas_seed.sql');

// Load the duas array by transpiling duas.ts in memory. The file only imports
// types, so a stub require() is enough to evaluate it.
function loadDuas() {
  const source = fs.readFileSync(duasFile, 'utf8');
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2020,
    },
    fileName: duasFile,
  });

  const moduleObject = { exports: {} };
  const requireStub = () => ({});
  new Function('exports', 'require', 'module', outputText)(
    moduleObject.exports,
    requireStub,
    moduleObject,
  );
  return moduleObject.exports.duas;
}

// Postgres string literal: single quotes are doubled.
function quote(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

// Postgres text[] literal.
function quoteArray(values) {
  return `ARRAY[${values.map(quote).join(', ')}]`;
}

function row(dua) {
  const columns = [
    quote(dua.id),
    quote(dua.category),
    quoteArray(dua.keywords),
    quote(dua.arabic),
    quote(dua.transliteration),
    quote(dua.translationEnglish),
    quote(dua.translationUrdu),
    quote(dua.reference),
    dua.verified ? 'TRUE' : 'FALSE',
  ];
  return `    (${columns.join(', ')})`;
}

function buildSql(duas) {
  return `-- Generated by scripts/generate-duas-seed.js. Do not edit by hand.
-- Source of truth: src/data/duas.ts (regenerate with: npm run seed:duas)
-- "verified" is written from src/data/duas.ts (the source of truth).

INSERT INTO duas (id, category, keywords, arabic, transliteration, translation_en, translation_ur, reference, verified)
VALUES
${duas.map(row).join(',\n')}
ON CONFLICT (id) DO UPDATE SET
    category = EXCLUDED.category,
    keywords = EXCLUDED.keywords,
    arabic = EXCLUDED.arabic,
    transliteration = EXCLUDED.transliteration,
    translation_en = EXCLUDED.translation_en,
    translation_ur = EXCLUDED.translation_ur,
    reference = EXCLUDED.reference,
    verified = EXCLUDED.verified;
`;
}

const duas = loadDuas();
if (!Array.isArray(duas) || duas.length === 0) {
  throw new Error('No duas found in src/data/duas.ts');
}

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, buildSql(duas), 'utf8');
console.log(`Wrote ${duas.length} duas to ${path.relative(root, outFile)}`);
